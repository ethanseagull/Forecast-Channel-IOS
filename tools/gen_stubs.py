"""Generate port/sdk/autostubs.c from the symbols a link reports as undefined.

- Functions (the SDK functions not ported yet) get a stub that logs its name
  once via port_stub_hit() and returns 0 in the integer / pointer register.
- Variables: Microsoft's C++ ABI puts a variable's type in its linker name
  (?name@@3<type>), and the decomp sometimes declares one global with
  different types or linkage in different units (CodeWarrior and the Itanium
  ABI ignore that). Such a reference is aliased (/alternatename) to the
  definition that does exist. Variables with no definition at all get a
  zeroed 256-byte block.

usage: py -I tools/gen_stubs.py <link log> <build dir> <llvm-nm>
  The log must come from a link with /demangle:no and /errorlimit:0
  (tools/build_windows.bat writes build_log.txt that way). Delete
  port/sdk/autostubs.c first to regenerate from scratch.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'port', 'sdk', 'autostubs.c')


def defined_symbols(build_dir, nm):
    objs = []
    for d, _, files in os.walk(build_dir):
        for f in files:
            if f.endswith('.obj') and not f.startswith('autostubs'):
                objs.append(os.path.join(d, f))
    out = subprocess.run([nm, '--defined-only', '--extern-only', '-j'] + objs,
                         capture_output=True, text=True).stdout
    return set(line.strip() for line in out.splitlines() if line.strip() and not line.endswith(':'))


def var_name(sym):
    # ?name@@3... is a global variable (no namespace) in the Microsoft ABI.
    m = re.match(r'^\?([A-Za-z_]\w*)@@3', sym)
    return m.group(1) if m else None


def c_str(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def main():
    log, build_dir, nm = sys.argv[1], sys.argv[2], sys.argv[3]
    text = open(log, encoding='utf-8', errors='replace').read()
    found = set(re.findall(r'undefined symbol: (\S+)', text))
    if not found:
        print('no undefined symbols in the log; autostubs.c unchanged')
        return
    defined = defined_symbols(build_dir, nm)
    by_var = {}
    for s in defined:
        v = var_name(s) or (s if re.match(r'^[A-Za-z_]\w*$', s) else None)
        if v:
            by_var.setdefault(v, []).append(s)

    funcs, aliases, datas = [], [], []
    for s in sorted(found):
        v = var_name(s)
        if v is None:
            funcs.append(s)
            continue
        targets = [t for t in by_var.get(v, []) if t != s]
        if targets:
            aliases.append((s, targets[0]))
        else:
            datas.append(s)

    lines = [
        '// Generated by tools/gen_stubs.py. Do not edit; port the function instead',
        '// (then regenerate).',
        '// Unported SDK functions log once via port_stub_hit and return 0.',
        'void port_stub_hit(const char* name);',
        '',
        '// Symbol names: Mach-O (iOS, macOS) prefixes C symbols with an underscore.',
        '#ifdef __APPLE__',
        '#define PORT_SYM(name) "_" name',
        '#else',
        '#define PORT_SYM(name) name',
        '#endif',
        '',
    ]
    if aliases:
        lines.append('// Globals declared with a different type or linkage than their definition.')
        lines.append("// MSVC mangling encodes a global's type; Itanium (Apple) does not.")
        lines.append('#ifdef _WIN32')
        for s, t in aliases:
            lines.append('#pragma comment(linker, "/alternatename:%s=%s")' % (c_str(s), c_str(t)))
        lines.append('#endif')
        lines.append('')
    for i, s in enumerate(datas):
        lines.append('__attribute__((used, aligned(32))) char port_stub_data_%d[256] __asm__(PORT_SYM("%s"));' % (i, c_str(s)))
    if datas:
        lines.append('')
    for i, s in enumerate(funcs):
        lines += [
            'long long port_stub_%d(void) __asm__(PORT_SYM("%s"));' % (i, c_str(s)),
            'long long port_stub_%d(void) {' % i,
            '    port_stub_hit("%s");' % c_str(s),
            '    return 0;',
            '}',
        ]
    open(OUT, 'w', newline='\n', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('stubs: %d functions, %d aliased globals, %d data blocks -> %s'
          % (len(funcs), len(aliases), len(datas), os.path.relpath(OUT, ROOT)))
    for s, t in aliases:
        print('  alias %s -> %s' % (s, t))
    for s in datas:
        print('  data  %s' % s)


if __name__ == '__main__':
    main()
